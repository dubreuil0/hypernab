  // follow the app's language setting (setLanguage).
  const supported = () => Object.keys(TEXTS);
  const guess = () => { const base = String(globalThis.navigator?.language || '').toLowerCase().split('-')[0]; return TEXTS[base] ? base : 'en'; };
  let current = guess();
  function t(key, vars) {
    const text = TEXTS[current]?.[key] ?? TEXTS.en[key] ?? key;
    return vars ? text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? '')) : text;
  }
  // Static markup: data-i18n="key" (text), data-i18n-title / -aria / -placeholder / -alt (attributes); data-t is the older text form.
  const ATTRIBUTES = { 'data-i18n-title': 'title', 'data-i18n-aria': 'aria-label', 'data-i18n-placeholder': 'placeholder', 'data-i18n-alt': 'alt' };
  function apply(root) {
    if (!root?.querySelectorAll) return;
    for (const node of root.querySelectorAll('[data-i18n], [data-t]')) node.textContent = t(node.dataset.i18n || node.dataset.t);
    for (const [from, to] of Object.entries(ATTRIBUTES)) for (const node of root.querySelectorAll(`[${from}]`)) node.setAttribute(to, t(node.getAttribute(from)));
  }
  // A text with a count: "<key>.one" for 1, "<key>.other" for the rest ({n} is the count). Languages without plural forms repeat the text.
  const tn = (key, count, vars) => t(`${key}.${count === 1 ? 'one' : 'other'}`, { n: count, ...vars });
  globalThis.HypernabText = { t, tn, TEXTS, apply, supported, language: () => current, setLanguage(code) { current = TEXTS[code] ? code : 'en'; } };
